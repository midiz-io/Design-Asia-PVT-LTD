import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import { format } from 'date-fns';
import { LOGO_BASE64 } from './logo';

export const generateInvoicePDF = (job: any, action: 'save' | 'open' = 'save') => {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();

  // 1. Company Header
  try {
    // Attach the logo beautifully on the top left of the Invoice
    doc.addImage(LOGO_BASE64, 'JPEG', 14, 15, 60, 20);
  } catch (e) {
    console.error('Could not add logo', e);
  }

  doc.setFontSize(22);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(15, 23, 42); // slate-900
  // Move text slightly down to avoid overlapping with the logo
  doc.text('DESIGN ASIA GROUP', 14, 45);

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(100);
  doc.text('123 Corporate Blvd, Business District', 14, 52);
  doc.text('Colombo, Sri Lanka', 14, 57);
  doc.text('Phone: +94 11 234 5678', 14, 62);
  doc.text('Email: info@designasia.biz', 14, 67);

  // 2. Invoice Title & Details
  doc.setFontSize(24);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(15, 23, 42);
  doc.text('INVOICE', pageWidth - 14, 35, { align: 'right' });

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(60);
  
  const invoiceNoText = `Invoice No: ${job.invoice_no || 'N/A'}`;
  const dateText = `Date: ${format(new Date(), 'dd/MM/yyyy')}`;
  const jobNoText = `Job No: ${job.job_number || 'N/A'}`;

  doc.text(invoiceNoText, pageWidth - 14, 45, { align: 'right' });
  doc.text(dateText, pageWidth - 14, 52, { align: 'right' });
  doc.text(jobNoText, pageWidth - 14, 59, { align: 'right' });

  // 3. Bill To Section
  doc.setDrawColor(226, 232, 240); // slate-200
  doc.setLineWidth(0.5);
  doc.line(14, 75, pageWidth - 14, 75);

  doc.setFontSize(11);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(15, 23, 42);
  doc.text('BILL TO:', 14, 85);

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(80);
  doc.text(`Customer Name: ${job.customer_name || 'N/A'}`, 14, 92);
  if (job.sales_person) {
    doc.text(`Sales Person: ${job.sales_person}`, 14, 98);
  }
  if (job.note) {
    // Word wrap the notes/description
    const splitNotes = doc.splitTextToSize(`Description: ${job.note}`, 100);
    doc.text(splitNotes, 14, 104);
  }

  // 4. Invoice Items Table
  const tableData = [
    [
      '1', 
      job.category ? `Design & Materials for ${job.category}` : 'General Design Services',
      job.quotation_value ? `Rs. ${Number(job.quotation_value).toLocaleString(undefined, { minimumFractionDigits: 2 })}` : 'N/A',
      job.invoice_amount ? `Rs. ${Number(job.invoice_amount).toLocaleString(undefined, { minimumFractionDigits: 2 })}` : 'Rs. 0.00'
    ]
  ];

  autoTable(doc, {
    startY: 125,
    head: [['#', 'Description', 'Quotation', 'Total Amount']],
    body: tableData,
    theme: 'plain',
    headStyles: { fillColor: [241, 245, 249], textColor: [15, 23, 42], fontStyle: 'bold', lineWidth: 0.1, lineColor: [226, 232, 240] },
    styles: { fontSize: 10, cellPadding: 8, textColor: [71, 85, 105], lineWidth: 0.1, lineColor: [226, 232, 240] },
    columnStyles: {
      0: { cellWidth: 15 },
      1: { cellWidth: 80 },
      2: { cellWidth: 50 },
      3: { cellWidth: 40, halign: 'right' }
    },
    alternateRowStyles: { fillColor: [255, 255, 255] },
  });

  // 5. Total Section
  const finalY = (doc as any).lastAutoTable.finalY + 15;
  
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(15, 23, 42);
  doc.text('Total Invoice Value:', pageWidth - 80, finalY, { align: 'right' });
  
  doc.setFontSize(14);
  doc.text(job.invoice_amount ? `Rs. ${Number(job.invoice_amount).toLocaleString(undefined, { minimumFractionDigits: 2 })}` : 'Rs. 0.00', pageWidth - 14, finalY, { align: 'right' });

  // 6. Footer / Notes
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(100);
  doc.text('Payment Terms: Due on receipt', 14, finalY + 20);
  doc.text('Thank you for your business!', 14, finalY + 26);
  
  // Footer Line
  doc.line(14, doc.internal.pageSize.getHeight() - 20, pageWidth - 14, doc.internal.pageSize.getHeight() - 20);
  doc.setFontSize(8);
  doc.text('Generated by TaskVision Enterprise Management System', pageWidth / 2, doc.internal.pageSize.getHeight() - 12, { align: 'center' });

  // 7. Output based on action
  if (action === 'open') {
    // Generate a blob URL and open it in a new tab for "Quick View"
    const pdfOutput = doc.output('bloburl');
    window.open(pdfOutput as any, '_blank');
  } else {
    // Save the file
    doc.save(`Invoice_${job.invoice_no || job.job_number}.pdf`);
  }
};
